/**
 * Discord OAuth Callback Function
 * Exchanges authorization code for access token
 */

exports.handler = async (event) => {
  const headers = {
    'Content-Type': 'application/json',
    'Access-Control-Allow-Origin': '*',
    'Access-Control-Allow-Methods': 'GET, OPTIONS',
    'Access-Control-Allow-Headers': 'Content-Type'
  };

  // Handle CORS preflight
  if (event.httpMethod === 'OPTIONS') {
    return { statusCode: 200, headers, body: '' };
  }

  if (event.httpMethod !== 'GET') {
    return {
      statusCode: 405,
      headers,
      body: JSON.stringify({ error: 'Method not allowed' })
    };
  }

  try {
    const { code, state } = event.queryStringParameters || {};

    // OAuth state is generated by the dashboard (crypto.randomUUID) and checked there.
    // Only a UUID is accepted, because it is embedded in the HTML below.
    const safeState = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(state || '') ? state : '';

    if (!code) {
      // No code - redirect to dashboard with error
      return {
        statusCode: 302,
        headers: { 'Location': '/dashboard.html?error=no_code' },
        body: ''
      };
    }

    const DISCORD_CLIENT_ID = '510775326310268930';
    const DISCORD_CLIENT_SECRET = process.env.DISCORD_CLIENT_SECRET;
    const REDIRECT_URI = process.env.REDIRECT_URI || 'https://ballidentifier.xyz/.netlify/functions/discord-oauth-callback';

    // Exchange code for access token
    const tokenResponse = await fetch('https://discord.com/api/v10/oauth2/token', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/x-www-form-urlencoded'
      },
      body: new URLSearchParams({
        client_id: DISCORD_CLIENT_ID,
        client_secret: DISCORD_CLIENT_SECRET,
        code: code,
        grant_type: 'authorization_code',
        redirect_uri: REDIRECT_URI,
        scope: 'identify guilds'
      })
    });

    if (!tokenResponse.ok) {
      const error = await tokenResponse.text();
      console.error('Discord token exchange error:', error);
      return {
        statusCode: 302,
        headers: { 'Location': '/dashboard.html?error=token_exchange_failed' },
        body: ''
      };
    }

    const tokenData = await tokenResponse.json();
    const accessToken = tokenData.access_token;

    const safeToken = JSON.stringify(accessToken);
    const html = `<!DOCTYPE html>
<html>
  <head>
    <meta charset="utf-8" />
    <title>Processing Discord Login...</title>
  </head>
  <body>
    <script>
      (function () {
        const token = ${safeToken};
        const state = ${JSON.stringify(safeState)};
        window.location.replace(
          '/dashboard.html#access_token=' + encodeURIComponent(token) + '&state=' + encodeURIComponent(state)
        );
      })();
    </script>
  </body>
</html>`;
    
    return {
      statusCode: 200,
      headers: {
        'Content-Type': 'text/html'
      },
      body: html
    };
  } catch (error) {
    console.error('OAuth callback error:', error);
    return {
      statusCode: 302,
      headers: {
        'Location': `/dashboard.html?error=${encodeURIComponent(error.message)}`
      },
      body: ''
    };
  }
};
